namespace MachineConnectionApi.Tests;

using System.Net;
using System.Security.Cryptography;
using System.Text.Json;
using MachineConnectionApi.Models;
using MachineConnectionApi.Services;

internal static class VerifyHttpTransferRegressionTests
{
    public static async Task RunAll()
    {
        var directory = Path.Combine(Path.GetTempPath(), "iott-http-transfer-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(directory);
        try
        {
            var file = new EvaluationFile { Id = Guid.NewGuid().ToString("N"), Name = "fixture.nc", SizeBytes = 1024 * 1024 };
            await File.WriteAllBytesAsync(Path.Combine(directory, file.Id + ".bin"), Enumerable.Repeat((byte)0x5a, (int)file.SizeBytes).ToArray());
            await File.WriteAllTextAsync(Path.Combine(directory, file.Id + ".json"), JsonSerializer.Serialize(file));
            var target = new VerifyMeasurementTarget
            {
                Id = "fixture", Protocol = "FTP", Host = "127.0.0.1", Port = 2121,
                Brand = "FTP", Model = "loopback-fixture", ConnectTimeoutMs = 10000, ReadTimeoutMs = 5000,
            };
            var handler = new TransferHandler(target);
            var adapter = new HttpVerifyMeasurementAdapter(new Factory(handler), directory);
            var progress = new List<double>();
            var result = await adapter.TransferAsync(target, file, "/verification", Name(), progress.Add, default);
            Require(result.Success && result.IntegrityVerified && result.HasEvidence && result.UploadedBytes == file.SizeBytes
                && result.UploadSeconds == 2.5 && handler.Uploads == 1 && handler.Snapshots == 1,
                "Production adapter must stream a real attachment through the verification contract, not always return Unsupported.");
            Require(progress.Count > 3 && progress[0] == 0 && progress[^1] == 1 && progress.SequenceEqual(progress.Order()),
                "HTTP upload progress must be bounded, monotonic and complete.");
            await adapter.TransferAsync(target, file, "/verification", Name(), _ => { }, default);
            Require(handler.Snapshots == 1 && handler.Uploads == 2, "One run must retain its original transfer configuration token across files.");
            handler.ConfigurationChanged = true;
            var changed = await adapter.TransferAsync(target, file, "/verification", Name(), _ => { }, default);
            Require(!changed.HasEvidence && handler.Snapshots == 1 && changed.Detail.Contains("配置"), "Changed Host configuration must fail closed without resnapshotting the run.");
            var afterChange = handler.Requests;
            await adapter.TransferAsync(target, file, "/verification", Name(), _ => { }, default);
            Require(handler.Requests == afterChange, "A detected configuration change must stop all subsequent writes in this run.");
            handler.ConfigurationChanged = false;
            target = new VerifyMeasurementTarget
            {
                Id = target.Id, Protocol = target.Protocol, Host = target.Host, Port = target.Port,
                Brand = target.Brand, Model = target.Model, ConnectTimeoutMs = target.ConnectTimeoutMs, ReadTimeoutMs = target.ReadTimeoutMs,
            }; // a new run, not a rebinding of the previous target
            foreach (var tamper in new[] { "hash", "device", "length", "readback", "time", "snapshot", "protocol" })
            {
                handler.Tamper = tamper;
                var invalidEvidence = await adapter.TransferAsync(target, file, "/verification", Name(), _ => { }, default);
                Require(!invalidEvidence.HasEvidence && !invalidEvidence.Success, "Unbound or inconsistent response must not be scored: " + tamper);
            }
            handler.Tamper = "";
            var requests = handler.Requests;
            Require(!(await adapter.TransferAsync(target, file, "/../user", Name(), _ => { }, default)).HasEvidence
                && !(await adapter.TransferAsync(target, file, "/verification", "O0001.nc", _ => { }, default)).HasEvidence
                && handler.Requests == requests, "Unsafe directory or filename must not even send an HTTP request.");
            var missing = file with { Id = Guid.NewGuid().ToString("N") };
            Require(!(await adapter.TransferAsync(target, missing, "/verification", Name(), _ => { }, default)).HasEvidence && handler.Requests == requests,
                "Missing real attachment must never be replaced by generated bytes.");
            var differentTarget = new VerifyMeasurementTarget
            {
                Id = target.Id, Protocol = target.Protocol, Host = "different.invalid", Port = target.Port,
                Brand = target.Brand, Model = target.Model, ConnectTimeoutMs = target.ConnectTimeoutMs, ReadTimeoutMs = target.ReadTimeoutMs,
            };
            var uploads = handler.Uploads;
            Require(!(await adapter.TransferAsync(differentTarget, file, "/verification", Name(), _ => { }, default)).HasEvidence && handler.Uploads == uploads,
                "Snapshot identity must be compared to the frozen selected target before writes.");
            using (var wrongProtocol = new TransferHandler(target) { SnapshotProtocol = "SMB" })
            {
                var mismatchAdapter = new HttpVerifyMeasurementAdapter(new Factory(wrongProtocol), directory);
                var freshTarget = new VerifyMeasurementTarget
                {
                    Id = target.Id, Protocol = target.Protocol, Host = target.Host, Port = target.Port,
                    Brand = target.Brand, Model = target.Model, ConnectTimeoutMs = target.ConnectTimeoutMs, ReadTimeoutMs = target.ReadTimeoutMs,
                };
                var mismatch = await mismatchAdapter.TransferAsync(freshTarget, file, "/verification", Name(), _ => { }, default);
                Require(!mismatch.HasEvidence && wrongProtocol.Uploads == 0,
                    "A Host snapshot for another protocol must not write or count toward configured FTP coverage.");
            }
            handler.BlockUpload = true;
            using var cancellation = new CancellationTokenSource(TimeSpan.FromMilliseconds(100));
            try
            {
                await adapter.TransferAsync(target, file, "/verification", Name(), _ => { }, cancellation.Token);
                throw new InvalidOperationException("Caller cancellation was swallowed.");
            }
            catch (OperationCanceledException) when (cancellation.IsCancellationRequested) { }
            await FileProtocolRoutesAsync(directory, file);
        }
        finally { Directory.Delete(directory, true); }
        Console.WriteLine("HTTP verification transfer adapter regressions passed (temporary attachments/fake HTTP only).");
    }

    private static async Task FileProtocolRoutesAsync(string directory, EvaluationFile file)
    {
        foreach (var protocol in new[] { "SMB", "NFS" })
        {
            var target = new VerifyMeasurementTarget
            {
                Id = "file-" + protocol, Protocol = protocol, Host = "fixture.invalid",
                Port = protocol == "SMB" ? 445 : 2049, Brand = protocol, Model = "HTTP-contract-fixture",
            };
            using var handler = new TransferHandler(target) { CleanupSucceeded = protocol != "NFS" };
            var adapter = new HttpVerifyMeasurementAdapter(new Factory(handler), directory);
            var result = await adapter.TransferAsync(target, file, "/verification", Name(), _ => { }, default);
            Require(result.Success && result.IntegrityVerified && result.HasEvidence && result.UploadedBytes == file.SizeBytes
                && handler.Uploads == 1 && handler.Snapshots == 1 && result.Detail.Contains(protocol),
                protocol + " frozen HTTP evidence was not accepted by the production adapter.");
            if (protocol != "NFS") continue;
            Require(result.Detail.Contains("清理未确认"), "NFS retained-file status disappeared from the adapter result.");
            using var rejected = new TransferHandler(target)
            {
                SnapshotSupported = false, SnapshotDetail = "NFS 挂载身份未确认：请配置实际 NFS 挂载。",
            };
            var unsupportedAdapter = new HttpVerifyMeasurementAdapter(new Factory(rejected), directory);
            result = await unsupportedAdapter.TransferAsync(target, file, "/verification", Name(), _ => { }, default);
            Require(!result.HasEvidence && !result.Success && rejected.Uploads == 0 && rejected.Snapshots == 1
                && result.Detail.Contains("实际 NFS 挂载"), "Unverified NFS mount sent an upload or lost its actionable reason.");
        }
    }

    private static string Name() => "verify-" + Guid.NewGuid().ToString("N") + ".nc";
    private static void Require(bool condition, string message) { if (!condition) throw new InvalidOperationException(message); }
    private sealed class Factory(HttpMessageHandler handler) : IHttpClientFactory
    {
        public HttpClient CreateClient(string name) => new(handler, disposeHandler: false) { BaseAddress = new Uri("http://127.0.0.1:1/") };
    }
    private sealed class TransferHandler(VerifyMeasurementTarget target) : HttpMessageHandler
    {
        public int Requests { get; private set; }
        public int Snapshots { get; private set; }
        public int Uploads { get; private set; }
        public bool ConfigurationChanged { get; set; }
        public bool BlockUpload { get; set; }
        public bool SnapshotSupported { get; set; } = true;
        public string SnapshotDetail { get; set; } = "";
        public string? SnapshotProtocol { get; set; }
        public bool CleanupSucceeded { get; set; } = true;
        public string Tamper { get; set; } = "";
        private const string Token = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef";
        protected override async Task<HttpResponseMessage> SendAsync(HttpRequestMessage request, CancellationToken ct)
        {
            Requests++;
            if (request.Method == HttpMethod.Get && request.RequestUri!.AbsolutePath.EndsWith("/verification/snapshot"))
            {
                Snapshots++;
                return Json(new
                {
                    deviceId = target.Id, token = Token, supported = SnapshotSupported, detail = SnapshotDetail,
                    protocol = SnapshotProtocol ?? target.Protocol, host = target.Host, port = target.Port,
                    primary = new
                    {
                        target.Protocol, target.Host, target.Port, target.Brand, target.Model, target.ConnectTimeoutMs,
                        target.ReadTimeoutMs, target.ExtendedProperties, target.Transfer,
                    },
                });
            }
            Require(request.Method == HttpMethod.Post && request.RequestUri!.AbsolutePath.EndsWith("/verification/round-trip"), "Adapter called an unsafe/legacy upload route.");
            if (BlockUpload) await Task.Delay(Timeout.InfiniteTimeSpan, ct);
            Uploads++;
            var form = request.Content as MultipartFormDataContent ?? throw new InvalidOperationException("Expected streaming multipart format.");
            var parts = form.ToDictionary(part => part.Headers.ContentDisposition!.Name!.Trim('"'));
            Require(await parts["allowWrites"].ReadAsStringAsync(ct) == "true" && await parts["snapshotToken"].ReadAsStringAsync(ct) == Token,
                "Explicit write grant and frozen token must be forwarded.");
            var remoteName = await parts["remoteName"].ReadAsStringAsync(ct);
            var expectedHash = await parts["expectedSha256"].ReadAsStringAsync(ct);
            var expectedLength = long.Parse(await parts["expectedBytes"].ReadAsStringAsync(ct), System.Globalization.CultureInfo.InvariantCulture);
            using var buffer = new MemoryStream(); // only this 1 MiB HTTP fixture, not production buffering
            await parts["file"].CopyToAsync(buffer, ct);
            var hash = Convert.ToHexString(SHA256.HashData(buffer.GetBuffer().AsSpan(0, (int)buffer.Length)));
            Require(buffer.Length == expectedLength && hash == expectedHash, "Adapter did not transmit the exact attachment bytes/hash.");
            if (ConfigurationChanged) return Json(new { supported = false, hasEvidence = false, success = false, configurationChanged = true, detail = "配置变化，未上传。" });
            return Json(new
            {
                supported = true, hasEvidence = true, success = true, integrityVerified = true,
                deviceId = Tamper == "device" ? "wrong" : target.Id,
                snapshotToken = Tamper == "snapshot" ? new string('a', 64) : Token,
                protocol = Tamper == "protocol" ? "wrong" : target.Protocol, remoteName, remotePath = "/verification/.iott-" + remoteName,
                uploadedBytes = Tamper == "length" ? expectedLength - 1 : expectedLength,
                downloadedBytes = expectedLength,
                uploadSeconds = Tamper == "time" ? 0 : 2.5,
                sourceSha256 = Tamper == "hash" ? new string('0', 64) : hash,
                readBackSha256 = Tamper == "readback" ? new string('1', 64) : hash,
                cleanupSucceeded = CleanupSucceeded, detail = CleanupSucceeded ? "本轮独占对象已清理。" : "测试文件已保留，清理未确认。",
            });
        }
        private static HttpResponseMessage Json(object value) => new(HttpStatusCode.OK)
        { Content = new StringContent(JsonSerializer.Serialize(value, new JsonSerializerOptions(JsonSerializerDefaults.Web)), System.Text.Encoding.UTF8, "application/json") };
    }
}
